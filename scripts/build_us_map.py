"""Build data/us-states.js (state outlines for the map page) from the us-atlas TopoJSON.

Usage:
    curl -O https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-10m.json
    python3 scripts/build_us_map.py states-10m.json
"""
import json
import sys
from pathlib import Path


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:  # quantized, delta-encoded
            x += dx
            y += dy
            pts.append([round(x * sx + tx, 3), round(y * sy + ty, 3)])
        arcs.append(pts)
    return arcs


def ring(arcs, idx):
    out = []
    for i in idx:
        pts = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(pts if not out else pts[1:])  # consecutive arcs share an endpoint
    return out


def main(src):
    topo = json.loads(Path(src).read_text())
    arcs = decode_arcs(topo)
    features = []
    for g in topo["objects"]["states"]["geometries"]:
        polys = [g["arcs"]] if g["type"] == "Polygon" else g["arcs"]
        coords = [[ring(arcs, r) for r in poly] for poly in polys]
        features.append({
            "type": "Feature",
            "properties": {"name": g["properties"]["name"]},
            "geometry": {"type": "MultiPolygon", "coordinates": coords},
        })
    out = Path(__file__).resolve().parent.parent / "data" / "us-states.js"
    out.write_text(
        "// Generated by scripts/build_us_map.py from us-atlas (US Census Bureau cartographic boundaries).\n"
        "window.US_STATES = " + json.dumps({"type": "FeatureCollection", "features": features}, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(features)} states to {out} ({out.stat().st_size // 1024} KB)", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
