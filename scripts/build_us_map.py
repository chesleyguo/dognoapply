"""Build data/us-states.js (state outlines for the map page) from the us-atlas TopoJSON.

Usage:
    curl -O https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-10m.json
    python3 scripts/build_us_map.py states-10m.json

The file keeps the TopoJSON form (quantized, delta-encoded arcs that neighboring states share), which is
about half the size of the same outlines as GeoJSON. js/map.js turns it into GeoJSON in the browser
(topoToGeo). Only the "states" object is kept.
"""
import json
import sys
from pathlib import Path


def main(src):
    topo = json.loads(Path(src).read_text())
    states = topo["objects"]["states"]
    used = sorted({~i if i < 0 else i
                   for g in states["geometries"]
                   for poly in ([g["arcs"]] if g["type"] == "Polygon" else g["arcs"])
                   for ring in poly for i in ring})
    # Drop arcs only the "nation" outline used, and renumber the rest.
    new = {old: k for k, old in enumerate(used)}
    remap = lambda i: ~new[~i] if i < 0 else new[i]  # noqa: E731
    geoms = []
    for g in states["geometries"]:
        polys = [g["arcs"]] if g["type"] == "Polygon" else g["arcs"]
        geoms.append({"name": g["properties"]["name"],
                      "arcs": [[[remap(i) for i in ring] for ring in poly] for poly in polys]})
    out = Path(__file__).resolve().parent.parent / "data" / "us-states.js"
    data = {"transform": topo["transform"], "arcs": [topo["arcs"][i] for i in used], "states": geoms}
    out.write_text(
        "// Generated by scripts/build_us_map.py from us-atlas (US Census Bureau cartographic boundaries).\n"
        "// TopoJSON-style: decoded to GeoJSON by topoToGeo() in js/map.js.\n"
        "window.US_TOPO = " + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(geoms)} states to {out} ({out.stat().st_size // 1024} KB)", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
